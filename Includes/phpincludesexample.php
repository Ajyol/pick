<p><strong>I. Text Server-Side Includes (or SSI)</strong><br>
  <strong>A. Create includes file for text:</strong><br>
    1. Set up a file folder in your site root folder if you haven&rsquo;t; name that folder &ldquo;Includes.&rdquo;<br>
    2. Create basic PHP page in Dreamweaver—no layout.<br>
    3. In Code View delete all opening and closing tags and metadata.<br>
    4. In Design View insert formatted text from Word file; do any further formatting.<br>
    5. Save with .php extension in Includes folder in site folder.<br>
  <strong>B. Set up text Include inside div on page:</strong><br>
    1. Create page from site with basic template of elements by saving a page file.<br>
    2.  Create div (Insert&gt;Layout&gt;Insert Div; leave class and label blank) in the intended <br>
              position on the page.<br>
    3. In Code View position cursor inside the newly-created div.<br>
    4. From Insert&gt;Common choose Server-Side Include.<br>
    3. In &ldquo;Select File&rdquo; window that pops up choose &ldquo;Document&rdquo; from the &ldquo;Relative to:&rdquo; <br>
              pulldown menu. Open the Includes folder and click on the appropriate Includes <br>
              file. Click the &ldquo;Open&rdquo; button; save with .php extension.<br>
    4. Check in Design view; resave as needed; put to server and check there.</p>
<p><strong>II. Spry Navbar Server-Side Includes</strong><br>
  <strong>A</strong>. <strong>Create includes file for navbar:</strong><br>
    1. Set up a file folder in your site root folder if you haven&rsquo;t; name that folder &ldquo;Includes.&rdquo;<br>
    2. Create a basic PHP page—no layout.<br>
    3. In Code View delete all opening and closing tags and metadata. <br>
    4. Open file with already-created Spry navbar.<br>
    5. In Design View click menu tag for the navbar.<br>
    6. Go to Code view, check that the entire block of navbar code is highlighted (adjust <br>
              if necessary to highlight entire block), then cut (Command/x) highlighted code.<br>
    7. Switch to Includes file; in Code view paste in navbar block of cut code.<br>
    8. Return to file with navbar;  In Code View cut (Command/x) Spry code at bottom of <br>
              head tag (above the opening body tag):<br>
  &lt;script src=&rdquo;SpryAssets/SpryMenuBar.js&rdquo; type=&rdquo;text/javascript&rdquo;&gt;&lt;/script&gt;<br>
    9. Return to new PHP Includes page, paste code at bottom of previously-added code.<br>
   10. Save with .php extension in Includes folder in site folder.<br>
  <strong>B. Set up navbar Include inside div on page</strong><br>
    2.  Create div (Insert&gt;Layout&gt;Insert Div; leave class and label blank) in the intended <br>
              navbar position on the main page.<br>
    3. In Code View position cursor inside the newly-created div.<br>
    4. From Insert&gt;Common choose Server-Side Include.<br>
    3. In &ldquo;Select File&rdquo; window that pops up choose &ldquo;Document&rdquo; from the &ldquo;Relative to:&rdquo; <br>
              pulldown menu. Open the Includes folder and click on the appropriate file. Click <br>
              the &ldquo;Open&rdquo; button.<br>
    4. Check in Design view; save with .php; put to server and check there.</p>
